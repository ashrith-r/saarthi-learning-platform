import { Router } from 'express';
import { requireLogin, requireSameOrigin, validateObjectIdParam } from '../middleware/middleware.js';
import * as practice from '../controllers/practiceController.js';
import {file} from '../controllers/materialController.js';
import * as c from '../controllers/studyController.js';
const router = Router();
router.use(['/dashboard', '/library', '/learn', '/planner', '/study-goal', '/practice', '/insights', '/revision','/materials'], requireLogin);
router.param('id', validateObjectIdParam('id'));
router.get('/dashboard', c.dashboard);
router.get('/library', c.library);
router.get('/learn/:id', c.workspace);
router.post('/learn/:id', requireSameOrigin, c.saveProgress);
router.get('/planner', c.planner);
router.post('/planner', requireSameOrigin, c.createTask);
router.post('/planner/:id', requireSameOrigin, c.changeTask);
router.post('/study-goal', requireSameOrigin, c.saveProfile);
router.get('/practice', practice.catalog);
router.post('/practice/start/:id', requireSameOrigin, practice.start);
router.get('/practice/run/:id', practice.show);
router.post('/practice/run/:id/save', requireSameOrigin, practice.save);
router.post('/practice/run/:id/submit', requireSameOrigin, practice.submit);
router.get('/insights', practice.insights);
router.post('/revision', requireSameOrigin, practice.revision);
router.get('/materials/:id',file);
export default router;
